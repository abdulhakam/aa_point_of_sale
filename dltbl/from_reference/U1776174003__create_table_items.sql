CREATE TABLE "items" (
    'id' BLOB PRIMARY KEY CHECK (is_uuid_v7(id)) NOT NULL,
    'image' TEXT NOT NULL DEFAULT '',
    'name' TEXT NOT NULL DEFAULT '',
    'itemCode' TEXT NOT NULL DEFAULT '',
    'itemGroup' BLOB REFERENCES 'item_groups'('id'),
    'for' TEXT NOT NULL DEFAULT '',
    'itemType' TEXT NOT NULL DEFAULT '',
    'unit' BLOB REFERENCES 'uoms'('id'),
    'rate' REAL NOT NULL DEFAULT 0,
    'description' TEXT NOT NULL DEFAULT '',
    'incomeAccount' BLOB REFERENCES 'accounts'('id'),
    'expenseAccount' BLOB REFERENCES 'accounts'('id'),
    'tax' BLOB REFERENCES 'taxes'('id'),
    'hsnCode' TEXT NOT NULL DEFAULT '',
    'barcode' TEXT NOT NULL DEFAULT '',
    'trackItem' INTEGER NOT NULL DEFAULT 0,
    'hasBatch' INTEGER NOT NULL DEFAULT 0,
    'batchSeries' TEXT NOT NULL DEFAULT '',
    'hasSerialNumber' INTEGER NOT NULL DEFAULT 0,
    'serialNumberSeries' TEXT NOT NULL DEFAULT '',
    'datafromErp' INTEGER NOT NULL DEFAULT 0,
    'created' TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK (datetime(created) IS NOT NULL),
    'updated' TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK (datetime(updated) IS NOT NULL)
) STRICT;