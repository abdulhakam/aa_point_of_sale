CREATE TABLE "accounting_settings" (
    'id' BLOB PRIMARY KEY CHECK (is_uuid_v7(id)) NOT NULL,
    'fullname' TEXT NOT NULL DEFAULT '',
    'companyName' TEXT NOT NULL DEFAULT '',
    'bankName' TEXT NOT NULL DEFAULT '',
    'country' TEXT NOT NULL DEFAULT '',
    'email' TEXT NOT NULL DEFAULT '',
    'writeOffAccount' BLOB REFERENCES 'accounts'('id'),
    'roundOffAccount' BLOB REFERENCES 'accounts'('id'),
    'discountAccount' BLOB REFERENCES 'accounts'('id'),
    'enableDiscounting' INTEGER NOT NULL DEFAULT 0,
    'enableInventory' INTEGER NOT NULL DEFAULT 0,
    'enablePriceList' INTEGER NOT NULL DEFAULT 0,
    'enableInvoiceReturns' INTEGER NOT NULL DEFAULT 0,
    'enableFormCustomization' INTEGER NOT NULL DEFAULT 0,
    'enableSync' INTEGER NOT NULL DEFAULT 0,
    'enableLead' INTEGER NOT NULL DEFAULT 0,
    'enablePricingRule' INTEGER NOT NULL DEFAULT 0,
    'enableItemEnquiry' INTEGER NOT NULL DEFAULT 0,
    'enableLoyaltyProgram' INTEGER NOT NULL DEFAULT 0,
    'enableCouponCode' INTEGER NOT NULL DEFAULT 0,
    'enableitemGroup' INTEGER NOT NULL DEFAULT 0,
    'enablePointOfSaleWithOutInventory' INTEGER NOT NULL DEFAULT 0,
    'enablePartialPayment' INTEGER NOT NULL DEFAULT 0,
    'fiscalYearStart' TEXT NOT NULL DEFAULT '',
    'fiscalYearEnd' TEXT NOT NULL DEFAULT '',
    'setupComplete' INTEGER NOT NULL DEFAULT 0,
    'created' TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK (datetime(created) IS NOT NULL),
    'updated' TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK (datetime(updated) IS NOT NULL)
) STRICT;